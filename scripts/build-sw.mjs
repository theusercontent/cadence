import { createHash } from 'node:crypto'
import { readFile, readdir, stat, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dist = path.join(root, 'dist')

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const files = []
  for (const entry of entries) {
    const full = path.join(directory, entry.name)
    if (entry.isDirectory()) files.push(...(await walk(full)))
    else files.push(full)
  }
  return files
}

async function buildServiceWorker() {
  const entries = await walk(dist)
  const assets = []
  const hash = createHash('sha256')

  for (const file of entries.sort()) {
    const relative = path.relative(dist, file).split(path.sep).join('/')
    if (relative === 'sw.js' || relative.endsWith('.map')) continue
    assets.push(`/${relative}`)
    const info = await stat(file)
    hash.update(`${relative}:${info.size}:${info.mtimeMs}`)
  }

  const version = hash.digest('hex').slice(0, 12)
  const cacheName = `cadence-shell-${version}`
  const body = `/* Generated by scripts/build-sw.mjs. Do not edit by hand. */
const CACHE_NAME = ${JSON.stringify(cacheName)};
const PRECACHE = ${JSON.stringify(assets, null, 2)};
const APP_SHELL = '/index.html';

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((key) => key.startsWith('cadence-shell-') && key !== CACHE_NAME).map((key) => caches.delete(key))),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(APP_SHELL, copy));
          return response;
        })
        .catch(async () => (await caches.match(request)) || (await caches.match(APP_SHELL)) || Response.error()),
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) return cached;
      return fetch(request).then((response) => {
        if (!response || response.status !== 200 || response.type === 'opaque') return response;
        const copy = response.clone();
        caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
        return response;
      });
    }),
  );
});
`

  await writeFile(path.join(dist, 'sw.js'), body, 'utf8')
  console.log(`Cadence service worker generated (${cacheName}, ${assets.length} assets).`)
}

buildServiceWorker().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
